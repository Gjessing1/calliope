#!/usr/bin/env node
/**
 * Calliope's app icon: an open book with a ribbon bookmark, in the flat style
 * of the sibling apps on this host (nodecal, maily, atlas) — brand-blue rounded
 * square, white shapes, darker blues for detail.
 *
 * The geometry is written once, in Android's 108×108 adaptive-icon canvas, and
 * rendered as vector drawables (sharp at every density, no PNGs to regenerate)
 * and as the web favicon SVG. The native project under apps/android/android is
 * generated and gitignored, so build-apk.sh runs this after `cap sync` every
 * time; an icon written into it by hand would vanish on the next regeneration.
 *
 *   node scripts/app-icon.mjs --android <res-dir>   # launcher icon resources
 *   node scripts/app-icon.mjs --svg <file>          # favicon / preview
 */
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const BLUE = '#2563EB';
const COVER = '#1E40AF';
const RIBBON = '#1E3A8A';
const PAGE = '#FFFFFF';
const LINE = '#93C5FD';
const GUTTER = '#DBEAFE';

// Everything a launcher may keep lies inside a 66-unit circle centred on the
// canvas; the book's corners sit on that circle so no mask shape clips them.
const cover =
  'M54,44 C47,39.5 37,38 27,38.5 V69.5 C37,69 47,70.5 54,74 C61,70.5 71,69 81,69.5 V38.5 C71,38 61,39.5 54,44 Z';
const leftPage = 'M54,41 C48,37 39,35.5 30,36 V66 C39,65.5 48,67 54,70 Z';
const rightPage = 'M54,41 C60,37 69,35.5 78,36 V66 C69,65.5 60,67 54,70 Z';
const gutter = 'M54,41 C55.5,40 57,39.2 58.5,38.6 V67.8 C57,68.4 55.5,69.1 54,70 Z';
const lines = [
  'M35,45 H48 A1,1 0 0 1 48,47 H35 A1,1 0 0 1 35,45 Z',
  'M35,50 H48 A1,1 0 0 1 48,52 H35 A1,1 0 0 1 35,50 Z',
  'M35,55 H48 A1,1 0 0 1 48,57 H35 A1,1 0 0 1 35,55 Z',
  'M35,60 H44 A1,1 0 0 1 44,62 H35 A1,1 0 0 1 35,60 Z',
  'M61,45 H68 A1,1 0 0 1 68,47 H61 A1,1 0 0 1 61,45 Z',
  'M61,50 H68 A1,1 0 0 1 68,52 H61 A1,1 0 0 1 61,50 Z',
  'M61,55 H68 A1,1 0 0 1 68,57 H61 A1,1 0 0 1 61,55 Z',
  'M61,60 H65 A1,1 0 0 1 65,62 H61 A1,1 0 0 1 61,60 Z',
];
const ribbon = 'M71,36.2 H75 V76 L73,74 L71,76 Z';

/** Painted bottom to top. */
const artwork = [
  [cover, COVER],
  [leftPage, PAGE],
  [rightPage, PAGE],
  [gutter, GUTTER],
  ...lines.map((d) => [d, LINE]),
  [ribbon, RIBBON],
];

/** The adaptive background is a colour; the legacy icon draws its own square. */
const roundedSquare = 'M24,0 H84 Q108,0 108,24 V84 Q108,108 84,108 H24 Q0,108 0,84 V24 Q0,0 24,0 Z';
/** Without the adaptive safe-zone margin the book can fill more of the square. */
const LEGACY_SCALE = 1.3;

const header = '<!-- Generated by scripts/app-icon.mjs; edit that, not this. -->';

function vector(paths, { scale = 1, background = null } = {}) {
  const body = paths
    .map(([d, fill]) => `        <path android:fillColor="${fill}" android:pathData="${d}" />`)
    .join('\n');
  const group =
    scale === 1
      ? body.replace(/^ {4}/gm, '')
      : `    <group android:pivotX="54" android:pivotY="54" android:scaleX="${scale}" android:scaleY="${scale}">\n${body}\n    </group>`;
  const square = background
    ? `    <path android:fillColor="${background}" android:pathData="${roundedSquare}" />\n`
    : '';
  return `<?xml version="1.0" encoding="utf-8"?>
${header}
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
${square}${group}
</vector>
`;
}

function adaptive() {
  return `<?xml version="1.0" encoding="utf-8"?>
${header}
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/calliope_icon_background" />
    <foreground android:drawable="@drawable/calliope_icon_foreground" />
    <monochrome android:drawable="@drawable/calliope_icon_monochrome" />
</adaptive-icon>
`;
}

function writeAndroid(res) {
  // Capacitor's template ships its own launcher icon as PNGs and adaptive XML
  // under the same names. Left in place, a density-specific PNG could still be
  // picked over ours by an older launcher, so they go.
  for (const dir of readdirSync(res)) {
    if (!dir.startsWith('mipmap')) continue;
    for (const file of readdirSync(path.join(res, dir))) {
      if (file.startsWith('ic_launcher')) rmSync(path.join(res, dir, file));
    }
  }
  const write = (dir, file, content) => {
    mkdirSync(path.join(res, dir), { recursive: true });
    writeFileSync(path.join(res, dir, file), content);
  };
  write('drawable', 'calliope_icon_foreground.xml', vector(artwork));
  // Themed icons (Android 13+) tint a single silhouette, so the spine has to
  // be a gap between the pages rather than a shade of blue.
  write(
    'drawable',
    'calliope_icon_monochrome.xml',
    vector([
      ['M52.8,41.8 C47,37.8 39,35.5 30,36 V66 C39,65.5 47,67.2 52.8,70 Z', '#FFFFFF'],
      ['M55.2,41.8 C61,37.8 69,35.5 78,36 V66 C69,65.5 61,67.2 55.2,70 Z', '#FFFFFF'],
      [ribbon, '#FFFFFF'],
    ]),
  );
  write(
    'drawable',
    'calliope_icon_legacy.xml',
    vector(artwork, { scale: LEGACY_SCALE, background: BLUE }),
  );
  write(
    'values',
    'calliope_icon.xml',
    `<?xml version="1.0" encoding="utf-8"?>
${header}
<resources>
    <color name="calliope_icon_background">${BLUE}</color>
</resources>
`,
  );
  // Android 8+ reads the adaptive icon; 6–7 fall back to the full-square vector.
  for (const name of ['ic_launcher.xml', 'ic_launcher_round.xml']) {
    write('mipmap-anydpi-v26', name, adaptive());
    write(
      'mipmap-anydpi',
      name,
      `<?xml version="1.0" encoding="utf-8"?>
${header}
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:drawable="@drawable/calliope_icon_legacy" />
</layer-list>
`,
    );
  }
}

function svg() {
  const body = artwork.map(([d, fill]) => `    <path fill="${fill}" d="${d}"/>`).join('\n');
  const offset = Number((54 - 54 * LEGACY_SCALE).toFixed(3));
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108">
  ${header}
  <path fill="${BLUE}" d="${roundedSquare}"/>
  <g transform="translate(${offset} ${offset}) scale(${LEGACY_SCALE})">
${body}
  </g>
</svg>
`;
}

const [flag, target] = process.argv.slice(2);
if (flag === '--android' && target) {
  writeAndroid(path.resolve(target));
  console.log(`launcher icon written to ${target}`);
} else if (flag === '--svg' && target) {
  writeFileSync(path.resolve(target), svg());
  console.log(`icon SVG written to ${target}`);
} else {
  console.error('usage: app-icon.mjs --android <res-dir> | --svg <file>');
  process.exit(1);
}
