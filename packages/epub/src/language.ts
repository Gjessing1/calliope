export interface LanguageNormalization {
  /** The normalized code, `''` when the input was empty. */
  code: string;
  /** Present when the code could not be confidently validated. */
  warning?: string;
  /** True when a 3-letter code was converted to its 2-letter equivalent. */
  converted?: boolean;
  /** The input as given, present only when `converted`. */
  original?: string;
}

/** Normalize a language code to BCP 47, preserving any region subtag. */
export function normalizeLanguageCode(code: string | null | undefined): LanguageNormalization {
  if (!code) return { code: '' };

  const original = code.trim();
  let normalized = original.toLowerCase();

  // Handle codes with region (e.g., en-US, en_US)
  const parts = normalized.split(/[-_]/);
  const rawBase = parts[0] ?? '';
  let baseLang = rawBase;
  const region = parts[1] ? parts[1].toUpperCase() : null;

  // If 3-letter code, try to convert to 2-letter
  const mapped = LANGUAGE_CODE_MAP[baseLang];
  if (baseLang.length === 3 && mapped) {
    baseLang = mapped;
  }

  // Reconstruct with region if present
  normalized = region ? `${baseLang}-${region}` : baseLang;

  // Validate the base language code
  if (baseLang.length === 2 && !VALID_BCP47_CODES.has(baseLang)) {
    return {
      code: normalized,
      warning: `Unknown language code: "${original}". Please verify this is a valid BCP 47 code.`,
    };
  }

  // Check if 3-letter code wasn't converted (unknown)
  if (rawBase.length === 3 && !LANGUAGE_CODE_MAP[rawBase]) {
    return {
      code: normalized,
      warning: `Could not convert 3-letter code "${rawBase}" to BCP 47 format. Please verify manually.`,
    };
  }

  // Check if conversion happened
  if (baseLang !== rawBase && rawBase.length === 3) {
    return { code: normalized, converted: true, original };
  }

  return { code: normalized };
}
